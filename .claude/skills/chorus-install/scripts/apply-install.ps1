param(
  # An unpacked build (win-unpacked) to mirror into InstallDir. Fast path; the default.
  [string]$AppDir = '',
  # An NSIS installer to run silently instead.
  [string]$InstallerPath = '',
  [Parameter(Mandatory)][string]$InstallDir,
  [Parameter(Mandatory)][string]$LogPath,
  [switch]$CloseRunning,
  # Give up waiting for the user to quit Chorus after this long.
  [int]$WaitHours = 12,
  # The installed app's profile (projects, settings, saved API keys). Backed up before every
  # install; the install is aborted if the backup fails. Neither install path touches it.
  [string]$UserDataDir = (Join-Path $env:APPDATA 'chorus')
)

$ErrorActionPreference = 'Stop'

# Regenerated by Chromium; everything else in the profile is kept.
$CacheDirs = @('Cache', 'Code Cache', 'GPUCache', 'DawnGraphiteCache', 'DawnWebGPUCache', 'Shared Dictionary')
# Written by the NSIS install; kept so Apps & Features can still uninstall Chorus.
$Uninstaller = 'Uninstall Chorus.exe'

function Write-Log([string]$message) {
  Add-Content -LiteralPath $LogPath -Encoding UTF8 -Value "$(Get-Date -Format o) $message"
}

function Backup-UserData {
  if (-not (Test-Path -LiteralPath $UserDataDir)) {
    Write-Log "no profile at $UserDataDir; nothing to back up"
    return
  }
  $backup = Join-Path (Split-Path $LogPath) ("userdata-backup-" + (Get-Date -Format 'yyyyMMdd-HHmmss'))
  New-Item -ItemType Directory -Path $backup -Force | Out-Null
  Get-ChildItem -LiteralPath $UserDataDir -Force |
    Where-Object { $CacheDirs -notcontains $_.Name -and $_.Name -ne 'lockfile' } |
    ForEach-Object { Copy-Item -LiteralPath $_.FullName -Destination $backup -Recurse -Force }
  Write-Log "backed up profile $UserDataDir to $backup"
}

function Get-InstalledChorus {
  $prefix = [IO.Path]::GetFullPath($InstallDir).TrimEnd('\') + '\'
  Get-Process -Name 'Chorus' -ErrorAction SilentlyContinue |
    Where-Object { $_.Path -and $_.Path.StartsWith($prefix, [StringComparison]::OrdinalIgnoreCase) }
}

function Install-FromAppDir {
  $sourceAsar = Get-Item -LiteralPath (Join-Path $AppDir 'resources\app.asar')
  # /MIR also deletes files the new build no longer ships. The uninstaller is excluded, which
  # keeps it from being purged.
  & robocopy.exe $AppDir $InstallDir /MIR /MT:16 /R:5 /W:2 /XF $Uninstaller /NFL /NDL /NP /NJH /NJS | Out-Null
  # robocopy: 0-7 are success (copied/extra/mismatched), 8+ are failures.
  if ($LASTEXITCODE -ge 8) { throw "robocopy failed with exit code $LASTEXITCODE" }
  $asar = Get-Item -LiteralPath (Join-Path $InstallDir 'resources\app.asar')
  if ($asar.Length -ne $sourceAsar.Length -or $asar.LastWriteTimeUtc -ne $sourceAsar.LastWriteTimeUtc) {
    throw "app.asar does not match the build ($($asar.Length) bytes, $($asar.LastWriteTime))."
  }
  Write-Log "installed from $AppDir (robocopy $LASTEXITCODE); app.asar $($asar.LastWriteTime)"
}

function Install-FromInstaller {
  $before = (Get-Item -LiteralPath (Join-Path $InstallDir 'resources\app.asar') -ErrorAction SilentlyContinue).LastWriteTime
  $proc = Start-Process -FilePath $InstallerPath -ArgumentList '/S' -Wait -PassThru
  if ($proc.ExitCode -ne 0) { throw "Installer exited with code $($proc.ExitCode)" }
  $asar = Get-Item -LiteralPath (Join-Path $InstallDir 'resources\app.asar')
  if ($before -and $asar.LastWriteTime -le $before) {
    throw "app.asar was not replaced (still $($asar.LastWriteTime))."
  }
  Write-Log "installed from $InstallerPath; app.asar $($asar.LastWriteTime)"
}

try {
  if ([bool]$AppDir -eq [bool]$InstallerPath) { throw 'Pass exactly one of -AppDir or -InstallerPath.' }
  Write-Log "helper started; source $AppDir$InstallerPath"

  if ($CloseRunning) {
    Write-Log 'closing running Chorus'
    Get-InstalledChorus | ForEach-Object { [void]$_.CloseMainWindow() }
    $deadline = (Get-Date).AddSeconds(20)
    while ((Get-InstalledChorus) -and (Get-Date) -lt $deadline) { Start-Sleep -Seconds 1 }
    Get-InstalledChorus | Stop-Process -Force -ErrorAction SilentlyContinue
  }

  $deadline = (Get-Date).AddHours($WaitHours)
  while (Get-InstalledChorus) {
    if ((Get-Date) -gt $deadline) { throw "Chorus was still running after $WaitHours h; not installed." }
    Start-Sleep -Seconds 2
  }
  Write-Log 'Chorus is not running; installing'
  Start-Sleep -Seconds 2
  Backup-UserData

  if ($AppDir) { Install-FromAppDir } else { Install-FromInstaller }

  Start-Process -FilePath (Join-Path $InstallDir 'Chorus.exe') -WorkingDirectory $InstallDir
  Write-Log 'relaunched Chorus; done'
} catch {
  Write-Log "FAILED: $($_.Exception.Message)"
  exit 1
}
