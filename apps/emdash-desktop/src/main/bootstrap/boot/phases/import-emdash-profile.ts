import {
  cpSync,
  existsSync,
  mkdirSync,
  readdirSync,
  rmSync,
  unlinkSync,
  writeFileSync,
} from 'node:fs';
import { join } from 'node:path';

/**
 * Chorus moved its profile from `%APPDATA%\emdash` to `%APPDATA%\chorus` when it was rebranded,
 * which left projects, settings and saved API keys behind. This imports the Emdash profile into
 * the Chorus profile exactly once per machine. It never touches the source, backs up any existing
 * Chorus profile first, and writes a marker so later launches (and upgrades) leave the profile
 * alone. Saved secrets stay readable because `Local State` (which holds the safeStorage key) is
 * copied along with the databases.
 */
export const PROFILE_IMPORT_MARKER = '.chorus-profile-import.json';

// Regenerated by Chromium, open during the pre-identity log line, or process locks.
const SKIPPED_ENTRIES = new Set([
  PROFILE_IMPORT_MARKER,
  'logs',
  'lockfile',
  'Cache',
  'Code Cache',
  'GPUCache',
  'DawnGraphiteCache',
  'DawnWebGPUCache',
  'Shared Dictionary',
]);
const APP_DATABASE = 'emdash4.db';

export type ProfileImportResult =
  | { kind: 'already-imported' }
  | { kind: 'nothing-to-import' }
  | { kind: 'imported'; backupPath: string | null }
  | { kind: 'deferred'; reason: string };

export function importEmdashProfileOnce({
  sourcePath,
  targetPath,
  now = new Date(),
}: {
  sourcePath: string;
  targetPath: string;
  now?: Date;
}): ProfileImportResult {
  const markerPath = join(targetPath, PROFILE_IMPORT_MARKER);
  if (existsSync(markerPath)) return { kind: 'already-imported' };

  if (!existsSync(join(sourcePath, APP_DATABASE))) {
    writeMarker(markerPath, { importedFrom: null, at: now.toISOString(), backupPath: null });
    return { kind: 'nothing-to-import' };
  }

  // A lockfile that cannot be removed belongs to a running instance whose databases are live.
  if (!releaseStaleLock(sourcePath)) {
    return { kind: 'deferred', reason: 'Emdash is running' };
  }
  if (!releaseStaleLock(targetPath)) {
    return { kind: 'deferred', reason: 'another Chorus instance is running' };
  }

  const existing = copyableEntries(targetPath);
  let backupPath: string | null = null;
  if (existing.length > 0) {
    backupPath = `${targetPath}.pre-import-backup-${now.toISOString().replace(/[:.]/g, '-')}`;
    mkdirSync(backupPath, { recursive: true });
    for (const entry of existing) {
      cpSync(join(targetPath, entry), join(backupPath, entry), { recursive: true });
    }
    // Stale -wal/-shm files would otherwise be replayed into the imported databases.
    for (const entry of existing) {
      rmSync(join(targetPath, entry), { recursive: true, force: true });
    }
  }

  mkdirSync(targetPath, { recursive: true });
  for (const entry of copyableEntries(sourcePath)) {
    cpSync(join(sourcePath, entry), join(targetPath, entry), { recursive: true });
  }

  // Written last: an interrupted import is retried on the next launch.
  writeMarker(markerPath, { importedFrom: sourcePath, at: now.toISOString(), backupPath });
  return { kind: 'imported', backupPath };
}

function copyableEntries(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).filter((entry) => !SKIPPED_ENTRIES.has(entry));
}

function releaseStaleLock(dir: string): boolean {
  const lockPath = join(dir, 'lockfile');
  if (!existsSync(lockPath)) return true;
  try {
    unlinkSync(lockPath);
    return true;
  } catch {
    return false;
  }
}

function writeMarker(markerPath: string, contents: Record<string, string | null>): void {
  mkdirSync(join(markerPath, '..'), { recursive: true });
  writeFileSync(markerPath, `${JSON.stringify(contents, null, 2)}\n`);
}
